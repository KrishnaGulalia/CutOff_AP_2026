-- Cutoff | CP2: PostgreSQL schema
-- Matches the 16 final relations in 01_normalization.md.
-- Run once in a development database:
--   psql -X -v ON_ERROR_STOP=1 -d cutoff_dev -f dbms/03_schema.sql
-- Creates an isolated `cutoff` namespace. No existing objects are dropped.
-- If this schema already exists, the transaction fails without replacing it.
-- See 02_schema_guide.md for the diagram, constraints and application rules.

BEGIN;
CREATE SCHEMA cutoff;
SET LOCAL search_path = cutoff, pg_catalog;

-- 1. Accounts and papers -------------------------------------------------------

CREATE TABLE users (
    user_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name        TEXT NOT NULL CHECK (btrim(user_name) <> ''),
    email            TEXT NOT NULL UNIQUE,
    password_hash    TEXT NOT NULL CHECK (btrim(password_hash) <> ''),
    user_created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_canonical CHECK (
        email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+$'
    ),
    CONSTRAINT users_timestamp_order CHECK (user_updated_at >= user_created_at)
);

CREATE TABLE tests (
    test_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_title        TEXT NOT NULL CHECK (btrim(test_title) <> ''),
    exam_year         SMALLINT NOT NULL CHECK (exam_year BETWEEN 2000 AND 9999),
    session_label     TEXT NOT NULL CHECK (btrim(session_label) <> ''),
    duration_minutes  INTEGER NOT NULL CHECK (duration_minutes > 0),
    test_created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Classification -----------------------------------------------------------

CREATE TABLE subjects (
    subject_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name  TEXT NOT NULL UNIQUE CHECK (btrim(subject_name) <> '')
);

CREATE TABLE chapters (
    chapter_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id    BIGINT NOT NULL REFERENCES subjects(subject_id) ON DELETE RESTRICT,
    chapter_name  TEXT NOT NULL CHECK (btrim(chapter_name) <> ''),
    CONSTRAINT chapters_name_per_subject UNIQUE (subject_id, chapter_name)
);

CREATE TABLE topics (
    topic_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id  BIGINT NOT NULL REFERENCES chapters(chapter_id) ON DELETE RESTRICT,
    topic_name  TEXT NOT NULL CHECK (btrim(topic_name) <> ''),
    CONSTRAINT topics_name_per_chapter UNIQUE (chapter_id, topic_name)
);

-- 3. Question content, options and answer keys ---------------------------------

CREATE TABLE questions (
    question_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id           BIGINT NOT NULL REFERENCES chapters(chapter_id) ON DELETE RESTRICT,
    question_text        TEXT NOT NULL CHECK (btrim(question_text) <> ''),
    question_type        TEXT NOT NULL CHECK (
        question_type IN ('SINGLE_CHOICE', 'MULTIPLE_SELECT', 'NUMERICAL')
    ),
    difficulty           TEXT NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard')),
    explanation_text     TEXT,
    question_created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE question_topics (
    question_id  BIGINT PRIMARY KEY REFERENCES questions(question_id) ON DELETE RESTRICT,
    topic_id     BIGINT NOT NULL REFERENCES topics(topic_id) ON DELETE RESTRICT
);

CREATE TABLE question_options (
    question_id  BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    option_label TEXT NOT NULL CHECK (option_label ~ '^[A-Z]$'),
    option_text  TEXT NOT NULL,
    PRIMARY KEY (question_id, option_label)
);

CREATE TABLE correct_options (
    question_id  BIGINT NOT NULL,
    option_label TEXT NOT NULL,
    PRIMARY KEY (question_id, option_label),
    FOREIGN KEY (question_id, option_label)
        REFERENCES question_options(question_id, option_label) ON DELETE RESTRICT
);

CREATE TABLE numerical_keys (
    question_id   BIGINT PRIMARY KEY REFERENCES questions(question_id) ON DELETE RESTRICT,
    accepted_min  NUMERIC NOT NULL,
    accepted_max  NUMERIC NOT NULL,
    CONSTRAINT numerical_keys_valid_interval CHECK (
        accepted_min <= accepted_max
        AND accepted_min NOT IN ('NaN'::NUMERIC, 'Infinity'::NUMERIC, '-Infinity'::NUMERIC)
        AND accepted_max NOT IN ('NaN'::NUMERIC, 'Infinity'::NUMERIC, '-Infinity'::NUMERIC)
    )
);

CREATE TABLE question_images (
    question_id     BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    image_position  INTEGER NOT NULL CHECK (image_position > 0),
    image_url       TEXT NOT NULL CHECK (btrim(image_url) <> ''),
    PRIMARY KEY (question_id, image_position)
);

CREATE TABLE option_images (
    question_id     BIGINT NOT NULL,
    option_label    TEXT NOT NULL,
    image_position  INTEGER NOT NULL CHECK (image_position > 0),
    image_url       TEXT NOT NULL CHECK (btrim(image_url) <> ''),
    PRIMARY KEY (question_id, option_label, image_position),
    FOREIGN KEY (question_id, option_label)
        REFERENCES question_options(question_id, option_label) ON DELETE RESTRICT
);

-- 4. Paper composition --------------------------------------------------------

CREATE TABLE test_questions (
    test_id            BIGINT NOT NULL REFERENCES tests(test_id) ON DELETE RESTRICT,
    question_id        BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    position           INTEGER NOT NULL CHECK (position > 0),
    marks_correct      NUMERIC NOT NULL DEFAULT 4,
    marks_incorrect    NUMERIC NOT NULL DEFAULT -1,
    marks_unattempted  NUMERIC NOT NULL DEFAULT 0,
    PRIMARY KEY (test_id, question_id),
    CONSTRAINT test_questions_position_unique UNIQUE (test_id, position),
    CONSTRAINT test_questions_signed_marks CHECK (
        marks_correct > 0 AND marks_correct < 'Infinity'::NUMERIC
        AND marks_incorrect <= 0 AND marks_incorrect > '-Infinity'::NUMERIC
        AND marks_unattempted = 0
    )
);

-- 5. Attempts and student responses -------------------------------------------

CREATE TABLE attempts (
    attempt_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    test_id         BIGINT NOT NULL REFERENCES tests(test_id) ON DELETE RESTRICT,
    started_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at    TIMESTAMPTZ,
    attempt_status  TEXT NOT NULL DEFAULT 'IN_PROGRESS',
    CONSTRAINT attempts_valid_state CHECK (
        (attempt_status = 'IN_PROGRESS' AND submitted_at IS NULL)
        OR (attempt_status = 'SUBMITTED' AND submitted_at IS NOT NULL
            AND submitted_at >= started_at)
    )
);

-- Repeated submitted attempts are allowed; concurrent active attempts are not.
CREATE UNIQUE INDEX attempts_one_active_per_user_test
    ON attempts(user_id, test_id) WHERE attempt_status = 'IN_PROGRESS';

CREATE TABLE answers (
    attempt_id          BIGINT NOT NULL REFERENCES attempts(attempt_id) ON DELETE RESTRICT,
    question_id         BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    numerical_response  NUMERIC,
    marked_for_review   BOOLEAN NOT NULL DEFAULT false,
    time_spent_seconds  INTEGER NOT NULL DEFAULT 0 CHECK (time_spent_seconds >= 0),
    answer_updated_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (attempt_id, question_id),
    CONSTRAINT answers_finite_number CHECK (
        numerical_response IS NULL OR numerical_response NOT IN (
            'NaN'::NUMERIC, 'Infinity'::NUMERIC, '-Infinity'::NUMERIC
        )
    )
);

CREATE TABLE answer_options (
    attempt_id   BIGINT NOT NULL,
    question_id  BIGINT NOT NULL,
    option_label TEXT NOT NULL,
    PRIMARY KEY (attempt_id, question_id, option_label),
    FOREIGN KEY (attempt_id, question_id)
        REFERENCES answers(attempt_id, question_id) ON DELETE RESTRICT,
    FOREIGN KEY (question_id, option_label)
        REFERENCES question_options(question_id, option_label) ON DELETE RESTRICT
);

-- 6. Cross-table checks --------------------------------------------------------
-- PK/FK/CHECK constraints cannot alone check paper membership or response type.
-- Locking the attempt serializes response writes against submission, including
-- writes to different selected-option rows for the same attempt.

CREATE FUNCTION cutoff.guard_response() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog, cutoff AS $$
DECLARE
    response_attempt BIGINT;
    response_question BIGINT;
    current_attempt cutoff.attempts%ROWTYPE;
    kind TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        response_attempt := OLD.attempt_id;
        response_question := OLD.question_id;
    ELSE
        response_attempt := NEW.attempt_id;
        response_question := NEW.question_id;
        IF TG_OP = 'UPDATE' AND
           (NEW.attempt_id, NEW.question_id) IS DISTINCT FROM
           (OLD.attempt_id, OLD.question_id) THEN
            RAISE EXCEPTION 'An answer cannot be moved to a different attempt or question'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    SELECT * INTO current_attempt FROM cutoff.attempts
        WHERE attempt_id = response_attempt FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Attempt % does not exist', response_attempt USING ERRCODE = '23503';
    END IF;
    IF current_attempt.attempt_status <> 'IN_PROGRESS' THEN
        RAISE EXCEPTION 'Submitted attempt % cannot be edited', response_attempt
            USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM cutoff.test_questions
        WHERE test_id = current_attempt.test_id AND question_id = response_question
    ) THEN
        RAISE EXCEPTION 'Question % is not in this attempt''s paper', response_question
            USING ERRCODE = '23514';
    END IF;
    SELECT question_type INTO kind FROM cutoff.questions WHERE question_id = response_question;

    IF TG_TABLE_NAME = 'answers' THEN
        IF kind <> 'NUMERICAL' AND NEW.numerical_response IS NOT NULL THEN
            RAISE EXCEPTION 'A choice question cannot have a numerical response'
                USING ERRCODE = '23514';
        END IF;
        NEW.answer_updated_at := clock_timestamp();
    ELSE
        IF kind = 'NUMERICAL' THEN
            RAISE EXCEPTION 'A numerical question cannot have selected options'
                USING ERRCODE = '23514';
        END IF;
        IF kind = 'SINGLE_CHOICE' THEN
            IF TG_OP = 'INSERT' AND EXISTS (
                SELECT 1 FROM cutoff.answer_options
                WHERE attempt_id = response_attempt AND question_id = response_question
            ) THEN
                RAISE EXCEPTION 'A single-choice response can contain only one option'
                    USING ERRCODE = '23514';
            ELSIF TG_OP = 'UPDATE' AND EXISTS (
                SELECT 1 FROM cutoff.answer_options
                WHERE attempt_id = response_attempt AND question_id = response_question
                  AND option_label <> OLD.option_label
            ) THEN
                RAISE EXCEPTION 'A single-choice response can contain only one option'
                    USING ERRCODE = '23514';
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER answers_guard BEFORE INSERT OR UPDATE OR DELETE ON answers
    FOR EACH ROW EXECUTE FUNCTION cutoff.guard_response();
CREATE TRIGGER answer_options_guard BEFORE INSERT OR UPDATE OR DELETE ON answer_options
    FOR EACH ROW EXECUTE FUNCTION cutoff.guard_response();

-- Changing selected options also changes the parent answer's last-updated time.
CREATE FUNCTION cutoff.touch_answer() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog, cutoff AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        UPDATE cutoff.answers SET answer_updated_at = clock_timestamp()
        WHERE attempt_id = OLD.attempt_id AND question_id = OLD.question_id;
        RETURN OLD;
    END IF;
    UPDATE cutoff.answers SET answer_updated_at = clock_timestamp()
    WHERE attempt_id = NEW.attempt_id AND question_id = NEW.question_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER answer_options_touch AFTER INSERT OR UPDATE OR DELETE ON answer_options
    FOR EACH ROW EXECUTE FUNCTION cutoff.touch_answer();

CREATE FUNCTION cutoff.guard_attempt() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog, cutoff AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.attempt_status <> 'IN_PROGRESS' THEN
            RAISE EXCEPTION 'A new attempt must start IN_PROGRESS' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.attempt_status = 'SUBMITTED' THEN
        RAISE EXCEPTION 'A submitted attempt is retained unchanged' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    IF (NEW.attempt_id, NEW.user_id, NEW.test_id, NEW.started_at) IS DISTINCT FROM
       (OLD.attempt_id, OLD.user_id, OLD.test_id, OLD.started_at) THEN
        RAISE EXCEPTION 'Attempt identity, owner, paper and start time are immutable'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER attempts_guard BEFORE INSERT OR UPDATE OR DELETE ON attempts
    FOR EACH ROW EXECUTE FUNCTION cutoff.guard_attempt();

CREATE FUNCTION cutoff.touch_user() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog, cutoff AS $$
BEGIN
    NEW.user_updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;
CREATE TRIGGER users_touch BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION cutoff.touch_user();

-- Topic membership is checked at transaction end, allowing a coordinated
-- reclassification to update the question and its topic together.
CREATE FUNCTION cutoff.check_topic_chapter() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog, cutoff AS $$
DECLARE
    target_question BIGINT;
    target_topic BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'topics' THEN
        target_topic := NEW.topic_id;
    ELSE
        target_question := NEW.question_id;
    END IF;
    IF EXISTS (
        SELECT 1 FROM cutoff.question_topics qt
        JOIN cutoff.questions q ON q.question_id = qt.question_id
        JOIN cutoff.topics t ON t.topic_id = qt.topic_id
        WHERE q.chapter_id <> t.chapter_id
          AND (q.question_id = target_question OR t.topic_id = target_topic)
    ) THEN
        RAISE EXCEPTION 'The assigned topic must belong to the question''s chapter'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER question_topics_chapter_check
    AFTER INSERT OR UPDATE ON question_topics DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION cutoff.check_topic_chapter();
CREATE CONSTRAINT TRIGGER questions_topic_chapter_check
    AFTER UPDATE ON questions DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION cutoff.check_topic_chapter();
CREATE CONSTRAINT TRIGGER topics_question_chapter_check
    AFTER UPDATE ON topics DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION cutoff.check_topic_chapter();

-- A publication/import transaction must validate answer-key completeness,
-- question subtypes and image-only options before making a paper available.
-- The application must also freeze content/mappings after an attempt starts.
-- These workflow rules are detailed in 02_schema_guide.md; this file does not
-- grant frontend access or create authentication/deployment policies.

COMMENT ON SCHEMA cutoff IS 'Cutoff AP project: normalized test-taking and analytics data';
COMMENT ON TABLE test_questions IS 'Reusable question placement and signed marking rules per paper';
COMMENT ON TABLE attempts IS 'Independent attempts; one active attempt per student and paper';
COMMENT ON TABLE answers IS 'Saved question state; no row means no saved state, not absence from paper';
COMMENT ON TABLE correct_options IS 'Private answer-key options; excluded from test-delivery payloads';
COMMENT ON TABLE numerical_keys IS 'Private inclusive numerical answer interval';
COMMENT ON COLUMN question_options.option_text IS 'May be empty only for an image-based option validated during publication';
COMMENT ON COLUMN test_questions.marks_incorrect IS 'Signed award, for example -1; do not negate it again';

COMMIT;
